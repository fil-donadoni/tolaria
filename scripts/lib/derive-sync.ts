/**
 * The decisions of `scripts/derive-sync.ts` (ADR 0157 § Option 1b, issue
 * #6247): which derived whole-file paths the base writes itself, whether a
 * regeneration on the tip owes a commit, what a push's outcome means, and
 * whether a tip is DERIVED-FRESH — the predicate `post-merge sync` moves the
 * primary checkout on. Pure; the regeneration, git and push I/O are the
 * script's.
 *
 * A LEAF on purpose: `land.ts` reads the subject and the paths to tell a
 * derive commit from a foreign push (`VERIFY_MERGED_TIP`), and must not drag
 * the compiler in. The path literals are pinned equal to their owners'
 * constants by `__tests__/derive-sync.test.ts`.
 */

/** The Oracle lockfile — its header hashes are the derived part. */
export const LOCKFILE_PATH = "data/oracle-compiled.json";

/**
 * The paths whose bytes summarise the WHOLE tree and so move on every PR
 * that changes any row (ADR 0157 § The problem): the lockfile (header
 * `compilerHash` / `registryHash` / `poolHash` / `botHash`) and the four
 * catalogue files. The base writes them after each merge; a PR will stop
 * carrying them (issue #6248).
 */
export const DERIVED_PATHS: readonly string[] = [
    LOCKFILE_PATH,
    "data/catalogue/source-hash.json",
    "data/catalogue/packed-corpus.json",
    "data/catalogue/definition-index.json",
    "data/catalogue/search-index.json",
];

/** The subject of the one commit `derive:sync` pushes straight to the base
 *  — `land` tells it from a foreign push by it and by its files. */
export const DERIVE_SYNC_COMMIT_SUBJECT =
    "derive:sync — regenerate the lockfile header and data/catalogue on the tip";

/** One derived path on the tip: what the tip commits there (null when the
 *  path is absent) and what a regeneration on that tree produces. Blob ids
 *  or bytes — the comparison is the same. */
export interface DerivedEntry {
    readonly path: string;
    readonly committed: string | null;
    readonly regenerated: string;
}

export type DerivePlan =
    | { readonly kind: "no-op" }
    | { readonly kind: "commit"; readonly paths: readonly string[] };

/**
 * Tip state → commit / no-op. A commit records exactly the paths whose
 * regenerated bytes differ from the tip's (a missing path counts as
 * differing); equal bytes everywhere is no commit at all — never an empty
 * commit, never a commit that touches an unchanged file. A path outside
 * {@link DERIVED_PATHS} is refused: the writer owns these five and nothing
 * else, whatever the regeneration also touched.
 */
export function derivePlan(entries: ReadonlyArray<DerivedEntry>): DerivePlan {
    const paths: string[] = [];
    for (const e of entries) {
        if (!DERIVED_PATHS.includes(e.path))
            throw new Error(
                `derive:sync owns ${DERIVED_PATHS.join(", ")} — not ${e.path}`
            );
        if (e.committed !== e.regenerated) paths.push(e.path);
    }
    return paths.length === 0 ? { kind: "no-op" } : { kind: "commit", paths };
}

/**
 * What a push's result means (ADR 0157 § Option 1b, "Coalescing"):
 *
 *   - `landed`: the base tip is the derive commit;
 *   - `coalesced`: the push was refused AND the base moved meanwhile — a
 *     newer tip exists, and its own post-merge run regenerates from scratch;
 *     this commit is dropped, never rebuilt or retried (the hourly cron is
 *     the backstop). Not a failure;
 *   - `failed`: the push was refused and the base did NOT move — the network,
 *     the credentials, a hook: the run's red.
 */
export function pushOutcome(input: {
    readonly pushed: boolean;
    readonly remoteMoved: boolean;
}): "landed" | "coalesced" | "failed" {
    if (input.pushed) return "landed";
    return input.remoteMoved ? "coalesced" : "failed";
}

/** A catalogue file on the tip beside what the tree generates for it. */
export interface CatalogueEntry {
    readonly path: string;
    readonly committed: string | null;
    readonly expected: string;
}

export type Freshness =
    | { readonly fresh: true }
    | { readonly fresh: false; readonly why: string };

/**
 * Is the tip DERIVED-FRESH — may the primary checkout (the local Convex
 * deployment) be fast-forwarded to it? Two questions, the two offline tiers
 * that cost about a second each: `check:oracle`'s header-hash tier
 * (`hashDrift`, the message `headerHashDrift` printed, or null) and
 * `catalogue:check`'s byte comparison of the four catalogue files. Any
 * drift is stale, with the first reason named; a stale tip leaves the primary
 * on the previous fresh tip (ADR 0157 § Option 1b, "Deployment").
 */
export function derivedFreshness(input: {
    readonly hashDrift: string | null;
    readonly catalogue: ReadonlyArray<CatalogueEntry>;
}): Freshness {
    if (input.hashDrift !== null)
        return {
            fresh: false,
            why: `lockfile header: ${input.hashDrift.split("\n")[0]!.trim()}`,
        };
    for (const c of input.catalogue)
        if (c.committed !== c.expected)
            return {
                fresh: false,
                why:
                    c.committed === null
                        ? `${c.path} is missing`
                        : `${c.path} is not what the tree generates`,
            };
    return { fresh: true };
}
