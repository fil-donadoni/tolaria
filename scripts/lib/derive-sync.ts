/**
 * The late issue's body (ADR 0159): what is late and since when, the commit
 * range that moved the Bot hash (`commits` are its Bot-source commits, `%h
 * %s` each, newest first), the latest `post-merge` runs (the replay's job
 * lives there), a push failure when the replay itself reported one, and the
 * filing stamp's `## Band` (standalone — no umbrella lends it one).
 */
export function renderDerivedLateIssue(input: {
    readonly sha: string;
    readonly kind: LateKind;
    readonly why: string;
    readonly sinceIso: string;
    readonly lateMinutes: number;
    readonly headerBotHash: string;
    readonly treeBotHash: string;
    readonly range: string;
    readonly commits: readonly string[];
    readonly runs: readonly string[];
    readonly pushFailure?: string;
}): string {
    const job =
        input.kind === "bot-hash"
            ? "`bot-replay` (`derive:sync --replay-bot`, `post-merge.yml`)"
            : "`housekeeping`'s drift sweep (`derive:sync`, `post-merge.yml`)";
    const commits =
        input.commits.length === 0
            ? "- (no Bot-source commit found in the range — the hash moved with the range itself)"
            : input.commits.map((c) => `- ${c}`).join("\n");
    const runs =
        input.runs.length === 0
            ? "- (could not list the runs — `gh run list --workflow post-merge.yml`)"
            : input.runs.map((r) => `- ${r}`).join("\n");
    return [
        "## Agent Brief",
        "",
        "**Category:** bug",
        `**Summary:** on \`${input.sha.slice(0, 10)}\` the derived Bot state is late by ${input.lateMinutes} min (stale since ${input.sinceIso}): ${input.why}. ${job} owes it and has not caught up within the grace. Health stays GREEN on the tree's own terms (ADR 0159, issue #6990) — nothing is blocked; the lockfile the sessions read is behind until the job lands.`,
        "",
        ...(input.pushFailure === undefined
            ? []
            : [
                  `**The replay ran and could not push:** ${input.pushFailure}. Its swept lockfile is the run's artifact (\`bot-replay-lockfile\`).`,
                  "",
              ]),
        `**Lockfile header Bot hash:** \`${input.headerBotHash}\`; **tree:** \`${input.treeBotHash}\`.`,
        "",
        `**Commit range that moved the Bot hash:** \`${input.range}\`, Bot-source commits:`,
        "",
        commits,
        "",
        "**Latest `post-merge` runs:**",
        "",
        runs,
        "",
        "**Desired behavior:** the job's next run lands its commit on the base (`gh workflow run post-merge.yml --ref staging -f job=bot-replay` re-dispatches the replay by hand; `-f job=housekeeping` the drift sweep). Once the header's Bot hash is the tree's and no `ready` row lacks a verdict, `derive:sync --settled` prints no late line and closes this issue itself on its next run (by title prefix). A run that keeps failing names the cause in its log — fix the runner, the push or the sweep, never the predicate.",
        "",
        "## Band",
        "",
        "P2 — nothing is blocked (ADR 0159): the tree is gated on its own terms; the Bot pool the sessions read stays on the previous state until the job catches up.",
        "",
    ].join("\n");
}

// ── The Bot-play replay on the base (issue #6463) ─────────────────────────
//
// A session's bare `oracle:compile` carries the committed Bot-play verdicts
// whatever the Bot hash says and plays only its graduations, so the
// header's Bot hash moves ONLY here: `derive:sync --replay-bot`, run by the
// `bot-replay` job of `post-merge.yml` after each merge and nightly, compares
// the header's hash with the tree's and, on a mismatch, replays every `ready`
// card once on that tip. The decisions are below; the sweep, git and `gh`
// are the script's.

/** What a replay commit may touch: the derived paths plus the card index. */
export const BOT_REPLAY_PATHS: readonly string[] = DERIVE_SYNC_PATHS;

/** The subject of the one commit the replay pushes to the base — `land`
 *  tells it from a foreign push by it and by its files, like the derive
 *  commit's. */
export const BOT_REPLAY_COMMIT_SUBJECT =
    "bot-replay — replay the Bot-play sweep on the base's tip";

/**
 * The base's own maintenance commits (issue #7417): `derive:sync` and the
 * Bot-play replay write derived state only, never a source. A PR's diff does
 * not own what they move (`check:derived-in-diff`), and no RED is theirs —
 * the RED ladder blames the PR commits before one, never the commit itself.
 */
export const BASE_MAINTENANCE_SUBJECTS: readonly string[] = [
    DERIVE_SYNC_COMMIT_SUBJECT,
    BOT_REPLAY_COMMIT_SUBJECT,
];

export function isBaseMaintenanceSubject(subject: string): boolean {
    return BASE_MAINTENANCE_SUBJECTS.includes(subject.trim());
}

export type BotReplayPlan =
    /** Header and tree agree: nothing to replay, seconds, no push. */
    | { readonly kind: "current" }
    /** This Bot already froze cards and its regression issue is open: not
     *  re-swept — the sweep would re-find the same `lost`. */
    | { readonly kind: "filed"; readonly issue: number }
    | { readonly kind: "sweep" };

/**
 * Whether the tip owes a replay. `openRegression` is the open regression
 * issue for THIS tree's Bot hash, if one exists — a Bot that already froze
 * cards is not swept again every hour until the issue is fixed: the fix
 * moves the hash.
 */
export function botReplayPlan(input: {
    readonly headerBotHash: string;
    readonly treeBotHash: string;
    readonly openRegression: number | null;
}): BotReplayPlan {
    if (input.headerBotHash === input.treeBotHash) return { kind: "current" };
    if (input.openRegression !== null)
        return { kind: "filed", issue: input.openRegression };
    return { kind: "sweep" };
}

/** A lockfile row as the replay's outcome reads it — the fields of
 *  `CardRow` it needs, so this leaf imports no lockfile type. */
export interface ReplayRow {
    readonly oracleId: string;
    readonly name: string;
    readonly state: string;
    readonly botReach?: string;
    readonly botGap?: string;
}

/** A card the replay took out of `ready`, with the verdict that did it. */
export interface LostCard {
    readonly oracleId: string;
    readonly name: string;
    readonly to: string;
    readonly verdict: string;
}

/**
 * What the sweep did to the `ready` set: `lost` is every card `ready`
 * before and not after (the Bot regression the replay must never write into
 * the lockfile silently), `gained` every card `ready` after and not before
 * (a card the Bot change unfroze — it owes a card-index row before the
 * catalogue packs). Both sorted by name. A card in `acknowledged` — the
 * oracle ids of `data/oracle-state-regressions.json`, a freeze a human ruled
 * correct — is not lost: `check:oracle` accepts the commit for it, and so
 * does the replay.
 */
export function botReplayOutcome(
    before: readonly ReplayRow[],
    after: readonly ReplayRow[],
    acknowledged: ReadonlySet<string> = new Set()
): { readonly lost: readonly LostCard[]; readonly gained: readonly string[] } {
    const wasReady = new Set(
        before
            .filter((r) => r.state === "ready" && !acknowledged.has(r.oracleId))
            .map((r) => r.oracleId)
    );
    const lost: LostCard[] = [];
    const gained: string[] = [];
    const seen = new Set<string>();
    for (const row of after) {
        seen.add(row.oracleId);
        const ready = row.state === "ready";
        if (wasReady.has(row.oracleId) && !ready)
            lost.push({
                oracleId: row.oracleId,
                name: row.name,
                to: row.state,
                verdict:
                    row.botReach === undefined
                        ? "(no verdict)"
                        : row.botGap === undefined
                          ? row.botReach
                          : `${row.botReach} — ${row.botGap}`,
            });
        else if (!wasReady.has(row.oracleId) && ready) gained.push(row.name);
    }
    for (const row of before)
        if (wasReady.has(row.oracleId) && !seen.has(row.oracleId))
            lost.push({
                oracleId: row.oracleId,
                name: row.name,
                to: "absent",
                verdict: "(row gone)",
            });
    const byName = (a: { name: string }, b: { name: string }) =>
        a.name < b.name ? -1 : a.name > b.name ? 1 : 0;
    return {
        lost: lost.sort(byName),
        gained: gained.sort(),
    };
}

/** The regression issue's title — one per Bot hash, so the open one is
 *  found by it and the same Bot is never filed twice. */
export function botRegressionTitle(treeBotHash: string): string {
    return `Bot regression: the replay under ${treeBotHash.replace(/^sha256:/, "").slice(0, 12)} took cards out of \`ready\``;
}

/** The labels the regression issue is stamped with at filing
 *  (`docs/agents/triage-labels.md` § Every new issue is stamped). */
export const BOT_REGRESSION_LABELS: readonly string[] = [
    "bug",
    "area:game-bot",
];

/**
 * The regression issue's body: the lost cards with their new verdicts, the
 * commit range that moved the Bot hash, and the filing stamp's `## Band`
 * (standalone — no umbrella lends it one). `commits` are the Bot-source
 * commits in `range`, `%h %s` each, newest first.
 */
export function renderBotRegressionIssue(input: {
    readonly sha: string;
    readonly headerBotHash: string;
    readonly treeBotHash: string;
    readonly range: string;
    readonly commits: readonly string[];
    readonly lost: readonly LostCard[];
}): string {
    const cards = input.lost
        .map(
            (c) =>
                `- **${c.name}** (\`${c.oracleId}\`) → \`${c.to}\`: ${c.verdict}`
        )
        .join("\n");
    const commits =
        input.commits.length === 0
            ? "- (no Bot-source commit found in the range — the hash moved with the range itself)"
            : input.commits.map((c) => `- ${c}`).join("\n");
    return [
        "## Agent Brief",
        "",
        "**Category:** bug",
        `**Summary:** \`derive:sync --replay-bot\` replayed the Bot-play sweep on \`${input.sha.slice(0, 10)}\` (header Bot hash \`${input.headerBotHash}\`, tree \`${input.treeBotHash}\`) and ${input.lost.length} card(s) left \`ready\` — a Bot regression (issue #6463). Nothing was committed: the lockfile on the base still carries the verdicts of the previous Bot.`,
        "",
        "**Cards no longer `ready`:**",
        "",
        cards,
        "",
        `**Commit range that moved the Bot hash:** \`${input.range}\`, Bot-source commits:`,
        "",
        commits,
        "",
        '**Desired behavior:** every card above plays again (`bun run oracle:compile --carry-bot --replay-card "<name>"` on the fix, a `must` blade entry per `/bot-change`) — the fix moves the Bot hash and the replay runs again on its own. A freeze ruled CORRECT is acknowledged in `data/oracle-state-regressions.json` (`bun run oracle:mark-regressions`, a human-written reason): the replay then commits without it. Closing this issue alone re-sweeps and re-files it.',
        "",
        "## Band",
        "",
        `P1 — ${input.lost.length} card(s) left \`ready\` under a Bot change: the pool shrank with no PR acknowledging it, and the lockfile header stays on the previous Bot until it is fixed.`,
        "",
    ].join("\n");
}

/**
 * What a push's result means (ADR 0157 § Option 1b, "Coalescing"):
 *
 *   - `landed`: the base tip is the derive commit;
 *   - `coalesced`: the push was refused AND the base moved meanwhile — a
 *     newer tip exists, and its own post-merge run regenerates from scratch;
 *     this commit is dropped, never rebuilt or retried (the hourly cron is
 *     the backstop). Not a failure;
 *   - `failed`: the push was refused and the base did NOT move — the network,
 *     the credentials, a hook: the run's red;
 *   - `off-base`: the push was refused because the commit was not built on the
 *     base tip but AHEAD of it — a feature branch's HEAD (issue #6765). A push
 *     there would land the branch's own commits with the derive commit,
 *     outside the queue and its lane. The run's red.
 */
export function pushOutcome(input: {
    readonly pushed: boolean;
    readonly remoteMoved: boolean;
    readonly headAheadOfBase?: boolean;
}): "landed" | "coalesced" | "failed" | "off-base" {
    if (input.pushed) return "landed";
    if (input.headAheadOfBase) return "off-base";
    return input.remoteMoved ? "coalesced" : "failed";
}

/** One git invocation, as `spawnSync` answers it; `timedOut` when its
 *  deadline passed. */
export interface GitAnswer {
    readonly status: number | null;
    readonly stdout: string;
    readonly stderr: string;
    readonly timedOut?: boolean;
}

/** Runs `git <args>` in the repository, with an optional deadline. */
export type GitRun = (args: string[], opts?: { timeout?: number }) => GitAnswer;

/** Git's own refusal line (` ! [rejected] … (non-fast-forward)`), never its
 *  multi-line `hint:` block. Pure. */
export function refusalLine(stderr: string, timedOutS?: number): string {
    if (timedOutS !== undefined) return `no answer within ${timedOutS}s`;
    const lines = stderr.split("\n").map((l) => l.trim());
    return (
        lines.find((l) => l.startsWith("! ")) ??
        lines.find((l) => l !== "" && !l.startsWith("hint:")) ??
        "git printed no error"
    );
}

/**
 * Push the derive commit `sha` (built on `head`) to the base and say what
 * happened — the I/O half of {@link pushOutcome}, over an injected runner so
 * a real bare remote can exercise it.
 *
 * The push is a COMPARE-AND-SWAP (issue #6765): it lands only while the base
 * tip is `head` itself. A plain push accepted any fast-forward, so a
 * `derive:sync` run on a feature branch rebased onto the base pushed the
 * branch's own commits with the derive commit — PR #6657 landed that way,
 * unqueued, on a RED base. On a refusal the base is fetched: a
 * remote tip that IS `sha` is a push that landed while the client timed out
 * (landed, not coalesced); any other tip but `head` is a base that moved
 * (coalesced); `head` itself is a refusal with the base unmoved (failed).
 *
 * `--no-verify` (issue #7150): the commit is regenerated state, never a
 * human's code, and `.husky/pre-push` runs the FULL gate on a push to the
 * branch the local `origin/HEAD` names — `staging` on a clone that follows
 * the remote's default, `main` on an older one. On the Huawei every derive
 * push ran `check:all` + `bun run test` inside the 120 s push deadline,
 * timed out, and was retried as transient: ~11 min, then exit 1.
 */
export function pushDerivedCommit(
    git: GitRun,
    input: {
        readonly sha: string;
        readonly head: string;
        readonly baseBranch: string;
        readonly originBase: string;
        readonly netTimeoutMs: number;
        /** Retry a TRANSIENT failure (a timeout, the network) this many
         *  times, sleeping `backoffMs[attempt]` before each (ADR 0159, issue
         *  #6990). Absent: one attempt, as before. */
        readonly retry?: PushRetry;
    }
): {
    readonly outcome: "landed" | "coalesced" | "failed" | "off-base";
    readonly why: string;
    readonly remoteTip: string;
    /** How many pushes were sent. */
    readonly attempts: number;
} {
    // A lease that matches skips git's fast-forward check, so a `sha` not
    // built on `head` would be a FORCE push: refused here, never sent.
    if (
        git(["merge-base", "--is-ancestor", input.head, input.sha]).status !== 0
    )
        return {
            outcome: "failed",
            why: `${input.sha.slice(0, 10)} is not built on ${input.head.slice(0, 10)} — not pushed`,
            remoteTip: input.head,
            attempts: 0,
        };
    const backoff = input.retry?.backoffMs ?? [];
    for (let attempt = 1; ; attempt++) {
        const push = git(
            [
                "push",
                "-q",
                "--no-verify",
                `--force-with-lease=refs/heads/${input.baseBranch}:${input.head}`,
                "origin",
                `${input.sha}:refs/heads/${input.baseBranch}`,
            ],
            { timeout: input.netTimeoutMs }
        );
        const why = refusalLine(
            push.stderr,
            push.timedOut ? input.netTimeoutMs / 1000 : undefined
        );
        if (push.status === 0)
            return {
                outcome: "landed",
                why,
                remoteTip: input.sha,
                attempts: attempt,
            };
        const fetched = git(["fetch", "-q", "origin", input.baseBranch], {
            timeout: input.netTimeoutMs,
        });
        const remoteTip =
            fetched.status === 0
                ? git(["rev-parse", input.originBase]).stdout.trim()
                : input.head;
        if (remoteTip === input.sha)
            return { outcome: "landed", why, remoteTip, attempts: attempt };
        const headAheadOfBase =
            remoteTip !== input.head &&
            git(["merge-base", "--is-ancestor", remoteTip, input.head])
                .status === 0;
        const outcome = pushOutcome({
            pushed: false,
            remoteMoved: remoteTip !== input.head,
            headAheadOfBase,
        });
        // Only a transient refusal with the base unmoved is worth a retry: a
        // moved base is coalesced (the caller re-bases), a hook's or a
        // lease's refusal repeats, a push the base has outrun is off-base.
        const wait = backoff[attempt - 1];
        if (
            outcome !== "failed" ||
            wait === undefined ||
            !transientPushFailure(push)
        )
            return {
                outcome,
                why: attempt > 1 ? `${why} (${attempt} attempts)` : why,
                remoteTip,
                attempts: attempt,
            };
        input.retry?.note?.(
            `push failed transiently (${why}) — retrying in ${Math.round(wait / 1000)}s (${attempt}/${backoff.length})`
        );
        input.retry?.sleep(wait);
    }
}

/** How a push retries a transient failure: the sleeps before each retry
 *  (their count is the retry count), the sleeper, a line per retry. */
export interface PushRetry {
    readonly backoffMs: readonly number[];
    readonly sleep: (ms: number) => void;
    readonly note?: (line: string) => void;
}

/** The backoff before each retry of a push that failed transiently (ADR
 *  0159, issue #6990): three retries, ~2.5 min in all — well inside the
 *  job's wall, long enough for a network blip to pass; on 2026-10-25 two
 *  75-min sweeps were discarded on one 120 s push timeout each. */
export const PUSH_RETRY_BACKOFF_MS: readonly number[] = [
    15_000, 45_000, 90_000,
];

/** git's and curl's lines for a failure that may pass on a retry — the
 *  network, the remote's availability — never a refusal (a hook, a lease,
 *  credentials: `unable to access … 403`, `RPC failed; HTTP 413`), which
 *  repeats. */
const TRANSIENT_PUSH =
    /could not resolve host|failed to connect|connection (timed out|reset|refused)|early eof|rpc failed; (curl \d+|http 5\d\d)|remote end hung up|operation timed out|ssl_error|gnutls|transfer closed|couldn't connect|returned error: 5\d\d/i;

/** Whether a failed push's answer is transient: a timeout, or stderr naming
 *  the network. Pure. */
export function transientPushFailure(push: GitAnswer): boolean {
    return push.timedOut === true || TRANSIENT_PUSH.test(push.stderr);
}

/** A catalogue file on the tip beside what the tree generates for it. */
export interface CatalogueEntry {
    readonly path: string;
    readonly committed: string | null;
    readonly expected: string;
}

export type Freshness =
    | { readonly fresh: true }
    | { readonly fresh: false; readonly why: string };

/**
 * Is the tip DERIVED-FRESH — may the primary checkout (the local Convex
 * deployment) be fast-forwarded to it? Two questions, the two offline tiers
 * that cost about a second each: `check:oracle`'s header-hash tier
 * (`hashDrift`, the message `headerHashDrift` printed, or null) and
 * `catalogue:check`'s byte comparison of the four catalogue files. Any
 * drift is stale, with the first reason named; a stale tip leaves the primary
 * on the previous fresh tip (ADR 0157 § Option 1b, "Deployment").
 */
export function derivedFreshness(input: {
    readonly hashDrift: string | null;
    readonly catalogue: ReadonlyArray<CatalogueEntry>;
}): Freshness {
    if (input.hashDrift !== null)
        return {
            fresh: false,
            why: `lockfile header: ${input.hashDrift.split("\n")[0]!.trim()}`,
        };
    for (const c of input.catalogue)
        if (c.committed !== c.expected)
            return {
                fresh: false,
                why:
                    c.committed === null
                        ? `${c.path} is missing`
                        : `${c.path} is not what the tree generates`,
            };
    return { fresh: true };
}
