/**
 * The decisions of `scripts/derive-sync.ts` (ADR 0157 § Option 1b, issue
 * #6247): which derived whole-file paths the base writes itself, whether a
 * regeneration on the tip owes a commit, what a push's outcome means, and
 * whether a tip is DERIVED-FRESH — the predicate `post-merge sync` moves the
 * primary checkout on. Pure; the regeneration, git and push I/O are the
 * script's.
 *
 * A LEAF on purpose: `land.ts` reads the subject and the paths to tell a
 * derive commit from a foreign push (`VERIFY_MERGED_TIP`), and must not drag
 * the compiler in. The path literals are pinned equal to their owners'
 * constants by `__tests__/derive-sync.test.ts`.
 */

/** The Oracle lockfile — its header hashes are the derived part. */
export const LOCKFILE_PATH = "data/oracle-compiled.json";

/**
 * The paths whose bytes summarise the WHOLE tree and so move on every PR
 * that changes any row (ADR 0157 § The problem): the lockfile (header
 * `compilerHash` / `registryHash` / `poolHash` / `botHash`) and the four
 * catalogue files. The base writes them after each merge; a PR will stop
 * carrying them (issue #6248).
 */
export const DERIVED_PATHS: readonly string[] = [
    LOCKFILE_PATH,
    "data/catalogue/source-hash.json",
    "data/catalogue/packed-corpus.json",
    "data/catalogue/definition-index.json",
    "data/catalogue/search-index.json",
];

/** The subject of the one commit `derive:sync` pushes straight to the base
 *  — `land` tells it from a foreign push by it and by its files. */
export const DERIVE_SYNC_COMMIT_SUBJECT =
    "derive:sync — regenerate the lockfile header and data/catalogue on the tip";

/** One derived path on the tip: what the tip commits there (null when the
 *  path is absent) and what a regeneration on that tree produces. Blob ids
 *  or bytes — the comparison is the same. */
export interface DerivedEntry {
    readonly path: string;
    readonly committed: string | null;
    readonly regenerated: string;
}

export type DerivePlan =
    | { readonly kind: "no-op" }
    | { readonly kind: "commit"; readonly paths: readonly string[] };

/**
 * Tip state → commit / no-op. A commit records exactly the paths whose
 * regenerated bytes differ from the tip's (a missing path counts as
 * differing); equal bytes everywhere is no commit at all — never an empty
 * commit, never a commit that touches an unchanged file. A path outside
 * `owned` ({@link DERIVED_PATHS}, or {@link BOT_REPLAY_PATHS} for the
 * replay) is refused: the writer owns these and nothing else, whatever the
 * regeneration also touched.
 */
export function derivePlan(
    entries: ReadonlyArray<DerivedEntry>,
    owned: readonly string[] = DERIVED_PATHS
): DerivePlan {
    const paths: string[] = [];
    for (const e of entries) {
        if (!owned.includes(e.path))
            throw new Error(
                `derive:sync owns ${owned.join(", ")} — not ${e.path}`
            );
        if (e.committed !== e.regenerated) paths.push(e.path);
    }
    return paths.length === 0 ? { kind: "no-op" } : { kind: "commit", paths };
}

// ── The drift sweep on the base (ADR 0158 § 2b, issue #6687) ──────────────
//
// A merge can leave `ready` rows whose Bot-play verdict was not played on the
// definition the tip compiles: two PRs that each moved one input of a card,
// a draft regenerated with `--carry-bot`, and — once a session carries drift
// verdicts (issue #6688) — every grammar PR. Those rows are the tip's MISSES
// (`probingBotReach`); the write path plays exactly them and commits the rows
// in its one derive commit.

/** The card index — `oracle:index` adds a row for a card that became `ready`
 *  on the base (the drift sweep's or the replay's), so their commits may
 *  carry it. Pinned equal to `POOL_PROJECTION_SOURCE` by test. */
export const CARD_INDEX_PATH = "data/card-index.json";

/** What the derive commit may touch: the derived paths, plus the card index
 *  when the drift sweep turned a card `ready` (issue #6687). `land` and
 *  `post-merge` tell the commit from a foreign push by its subject and these
 *  files. */
export const DERIVE_SYNC_PATHS: readonly string[] = [
    ...DERIVED_PATHS,
    CARD_INDEX_PATH,
];

/** What one drift sweep did, for the log and the job summary. */
export interface DriftSweep {
    readonly sha: string;
    /** The tip's misses before the play. */
    readonly misses: number;
    /** The misses whose row carries a verdict after it. */
    readonly played: number;
    readonly wallMs: number;
    /** Cards the sweep took out of `ready` — committed, the Bot Gap is
     *  `gaps:sync`'s to file (ADR 0158 § Consequences). */
    readonly lost: readonly LostCard[];
    /** Cards that became `ready` — `oracle:index` owes them a row. */
    readonly gained: readonly string[];
}

/** The ids among `misses` whose row in `after` carries a verdict: what the
 *  sweep actually played, read off the file it wrote. */
export function playedMisses(
    misses: ReadonlySet<string>,
    after: readonly ReplayRow[]
): number {
    let played = 0;
    for (const row of after)
        if (misses.has(row.oracleId) && row.botReach !== undefined) played += 1;
    return played;
}

/** The drift sweep as one line for the log and a Markdown block for
 *  `$GITHUB_STEP_SUMMARY`. */
export function renderDriftSweep(sweep: DriftSweep): {
    readonly line: string;
    readonly summary: string;
} {
    const wall = `${Math.round(sweep.wallMs / 1000)}s`;
    const line = `${sweep.sha.slice(0, 10)}: drift sweep — ${sweep.misses} miss(es), ${sweep.played} played, ${wall}${sweep.lost.length > 0 ? `; ${sweep.lost.length} left \`ready\`: ${sweep.lost.map((c) => c.name).join(", ")}` : ""}${sweep.gained.length > 0 ? `; ${sweep.gained.length} newly \`ready\`` : ""}`;
    const summary = [
        `### derive:sync — drift sweep on \`${sweep.sha.slice(0, 10)}\``,
        "",
        "| misses | played | wall | left `ready` | newly `ready` |",
        "| -----: | -----: | ---: | -----------: | ------------: |",
        `| ${sweep.misses} | ${sweep.played} | ${wall} | ${sweep.lost.length} | ${sweep.gained.length} |`,
        "",
        ...(sweep.lost.length > 0
            ? [
                  "Left `ready` (the Bot Gap is `gaps:sync`'s to file):",
                  "",
                  ...sweep.lost.map(
                      (c) => `- **${c.name}** → \`${c.to}\`: ${c.verdict}`
                  ),
                  "",
              ]
            : []),
    ].join("\n");
    return { line, summary };
}

/** The drift sweep's I/O, injected: the script wires the generators and the
 *  lockfile on disk, a test a fixture. */
export interface DriftSweepIo {
    readonly head: string;
    /** The lockfile on disk — the tip's before the play, the sweep's after. */
    readonly readRows: () => readonly ReplayRow[];
    /** The tip's misses (`staleVerdicts`), read before anything is written. */
    readonly misses: () => ReadonlySet<string>;
    /** `oracle:compile --carry-bot`: writes, never plays. */
    readonly carry: () => boolean;
    /** Bare `oracle:compile`: plays exactly the misses. */
    readonly play: () => boolean;
    /** `oracle:index`: a row for every card newly `ready`. */
    readonly index: () => boolean;
    readonly acknowledged: ReadonlySet<string>;
    readonly now: () => number;
    readonly report: (rendered: {
        readonly line: string;
        readonly summary: string;
    }) => void;
    /** A failure the run survives, said once. */
    readonly warn: (line: string) => void;
}

/** What step 1 left: `ok` false only when not even the carry wrote the
 *  lockfile; `indexed` when `oracle:index` ran, so the commit may carry the
 *  card index — and only then. */
export interface DriftSweepResult {
    readonly ok: boolean;
    readonly indexed: boolean;
}

/**
 * Step 1 of the write path (ADR 0158 § 2b, issue #6687): zero misses carry,
 * as the write path always did — seconds, nothing played; any miss is played
 * by the bare compile and a card it brought into `ready` indexed. Reported
 * either way. A play or an index that fails (a wall, machine admission's
 * exit 77, Scryfall) falls back to the carry: the header and catalogue
 * commit must still land — a stale verdict never holds the deployment (ADR
 * 0158 § 2b) — and the misses stay stale, which health waits on through
 * `--settled` and reds past the grace. `lost` is read over the misses only:
 * a card that left `ready` for a compiler or registry reason is not the
 * sweep's.
 */
export function runDriftSweep(io: DriftSweepIo): DriftSweepResult {
    const misses = io.misses();
    const carried = (why: string | null): DriftSweepResult => {
        if (why !== null)
            io.warn(
                `${why} — carrying the verdicts instead: the header and catalogue still land, the ${misses.size} miss(es) stay stale for the next run (health waits on them, ADR 0158 § 2b)`
            );
        return { ok: io.carry(), indexed: false };
    };
    if (misses.size === 0) {
        const result = carried(null);
        if (result.ok)
            io.report(
                renderDriftSweep({
                    sha: io.head,
                    misses: 0,
                    played: 0,
                    wallMs: 0,
                    lost: [],
                    gained: [],
                })
            );
        return result;
    }
    const before = io.readRows();
    const started = io.now();
    if (!io.play()) return carried("the drift sweep's compile failed");
    const after = io.readRows();
    const outcome = botReplayOutcome(before, after, io.acknowledged);
    io.report(
        renderDriftSweep({
            sha: io.head,
            misses: misses.size,
            played: playedMisses(misses, after),
            wallMs: io.now() - started,
            lost: outcome.lost.filter((c) => misses.has(c.oracleId)),
            gained: outcome.gained,
        })
    );
    if (outcome.gained.length === 0) return { ok: true, indexed: false };
    if (io.index()) return { ok: true, indexed: true };
    return carried("`oracle:index` failed for the newly `ready` card(s)");
}

/**
 * Health's question beside {@link derivedFreshness} (ADR 0158 § 2b): are the
 * tip's Bot-play verdicts CURRENT? Stale when a `ready` row carries no
 * verdict for the definition the tip compiles (`stale`, card names: the
 * drift sweep's to play) or when the header's Bot hash is not the tree's
 * (`--replay-bot`'s to replay) — unless this Bot's regression issue is open:
 * the replay already ran and refused to commit, and waiting on it is waiting
 * on a Bot fix, not on the writer. The deployment never asks this
 * (`derive:sync --fresh`): a stale verdict breaks no game.
 */
export function verdictCurrency(input: {
    readonly stale: readonly string[];
    readonly headerBotHash: string;
    readonly treeBotHash: string;
    readonly openRegression: number | null;
}): Freshness {
    if (input.stale.length > 0) {
        const shown = input.stale.slice(0, 5).join(", ");
        const more =
            input.stale.length > 5 ? `, … ${input.stale.length - 5} more` : "";
        return {
            fresh: false,
            why: `${input.stale.length} \`ready\` row(s) carry no Bot verdict for the definition the tip compiles (${shown}${more}) — derive:sync's drift sweep plays them`,
        };
    }
    if (
        input.headerBotHash !== input.treeBotHash &&
        input.openRegression === null
    )
        return {
            fresh: false,
            why: `the lockfile header's Bot hash ${input.headerBotHash.slice(0, 19)} is not the tree's ${input.treeBotHash.slice(0, 19)} — derive:sync --replay-bot replays the catalogue`,
        };
    return { fresh: true };
}

/** The line `--fresh` / `--settled` print on a stale tree — the one
 *  `derivePredicateAnswer` (`lib/health-step.ts`) reads the reason from. */
export function derivedStaleLine(why: string): string {
    return `derive:sync: this tree is derived-stale — ${why}`;
}

// ── The Bot-play replay on the base (issue #6463) ─────────────────────────
//
// A session's bare `oracle:compile` carries the committed Bot-play verdicts
// whatever the Bot hash says and plays only its definition misses, so the
// header's Bot hash moves ONLY here: `derive:sync --replay-bot`, run by the
// `bot-replay` job of `post-merge.yml` after each merge and nightly, compares
// the header's hash with the tree's and, on a mismatch, replays every `ready`
// card once on that tip. The decisions are below; the sweep, git and `gh`
// are the script's.

/** What a replay commit may touch: the derived paths plus the card index. */
export const BOT_REPLAY_PATHS: readonly string[] = DERIVE_SYNC_PATHS;

/** The subject of the one commit the replay pushes to the base — `land`
 *  tells it from a foreign push by it and by its files, like the derive
 *  commit's. */
export const BOT_REPLAY_COMMIT_SUBJECT =
    "bot-replay — replay the Bot-play sweep on the base's tip";

export type BotReplayPlan =
    /** Header and tree agree: nothing to replay, seconds, no push. */
    | { readonly kind: "current" }
    /** This Bot already froze cards and its regression issue is open: not
     *  re-swept — the sweep would re-find the same `lost`. */
    | { readonly kind: "filed"; readonly issue: number }
    | { readonly kind: "sweep" };

/**
 * Whether the tip owes a replay. `openRegression` is the open regression
 * issue for THIS tree's Bot hash, if one exists — a Bot that already froze
 * cards is not swept again every hour until the issue is fixed: the fix
 * moves the hash.
 */
export function botReplayPlan(input: {
    readonly headerBotHash: string;
    readonly treeBotHash: string;
    readonly openRegression: number | null;
}): BotReplayPlan {
    if (input.headerBotHash === input.treeBotHash) return { kind: "current" };
    if (input.openRegression !== null)
        return { kind: "filed", issue: input.openRegression };
    return { kind: "sweep" };
}

/** A lockfile row as the replay's outcome reads it — the fields of
 *  `CardRow` it needs, so this leaf imports no lockfile type. */
export interface ReplayRow {
    readonly oracleId: string;
    readonly name: string;
    readonly state: string;
    readonly botReach?: string;
    readonly botGap?: string;
}

/** A card the replay took out of `ready`, with the verdict that did it. */
export interface LostCard {
    readonly oracleId: string;
    readonly name: string;
    readonly to: string;
    readonly verdict: string;
}

/**
 * What the sweep did to the `ready` set: `lost` is every card `ready`
 * before and not after (the Bot regression the replay must never write into
 * the lockfile silently), `gained` every card `ready` after and not before
 * (a card the Bot change unfroze — it owes a card-index row before the
 * catalogue packs). Both sorted by name. A card in `acknowledged` — the
 * oracle ids of `data/oracle-state-regressions.json`, a freeze a human ruled
 * correct — is not lost: `check:oracle` accepts the commit for it, and so
 * does the replay.
 */
export function botReplayOutcome(
    before: readonly ReplayRow[],
    after: readonly ReplayRow[],
    acknowledged: ReadonlySet<string> = new Set()
): { readonly lost: readonly LostCard[]; readonly gained: readonly string[] } {
    const wasReady = new Set(
        before
            .filter((r) => r.state === "ready" && !acknowledged.has(r.oracleId))
            .map((r) => r.oracleId)
    );
    const lost: LostCard[] = [];
    const gained: string[] = [];
    const seen = new Set<string>();
    for (const row of after) {
        seen.add(row.oracleId);
        const ready = row.state === "ready";
        if (wasReady.has(row.oracleId) && !ready)
            lost.push({
                oracleId: row.oracleId,
                name: row.name,
                to: row.state,
                verdict:
                    row.botReach === undefined
                        ? "(no verdict)"
                        : row.botGap === undefined
                          ? row.botReach
                          : `${row.botReach} — ${row.botGap}`,
            });
        else if (!wasReady.has(row.oracleId) && ready) gained.push(row.name);
    }
    for (const row of before)
        if (wasReady.has(row.oracleId) && !seen.has(row.oracleId))
            lost.push({
                oracleId: row.oracleId,
                name: row.name,
                to: "absent",
                verdict: "(row gone)",
            });
    const byName = (a: { name: string }, b: { name: string }) =>
        a.name < b.name ? -1 : a.name > b.name ? 1 : 0;
    return {
        lost: lost.sort(byName),
        gained: gained.sort(),
    };
}

/** The regression issue's title — one per Bot hash, so the open one is
 *  found by it and the same Bot is never filed twice. */
export function botRegressionTitle(treeBotHash: string): string {
    return `Bot regression: the replay under ${treeBotHash.replace(/^sha256:/, "").slice(0, 12)} took cards out of \`ready\``;
}

/** The labels the regression issue is stamped with at filing
 *  (`docs/agents/triage-labels.md` § Every new issue is stamped). */
export const BOT_REGRESSION_LABELS: readonly string[] = [
    "bug",
    "area:game-bot",
];

/**
 * The regression issue's body: the lost cards with their new verdicts, the
 * commit range that moved the Bot hash, and the filing stamp's `## Band`
 * (standalone — no umbrella lends it one). `commits` are the Bot-source
 * commits in `range`, `%h %s` each, newest first.
 */
export function renderBotRegressionIssue(input: {
    readonly sha: string;
    readonly headerBotHash: string;
    readonly treeBotHash: string;
    readonly range: string;
    readonly commits: readonly string[];
    readonly lost: readonly LostCard[];
}): string {
    const cards = input.lost
        .map(
            (c) =>
                `- **${c.name}** (\`${c.oracleId}\`) → \`${c.to}\`: ${c.verdict}`
        )
        .join("\n");
    const commits =
        input.commits.length === 0
            ? "- (no Bot-source commit found in the range — the hash moved with the range itself)"
            : input.commits.map((c) => `- ${c}`).join("\n");
    return [
        "## Agent Brief",
        "",
        "**Category:** bug",
        `**Summary:** \`derive:sync --replay-bot\` replayed the Bot-play sweep on \`${input.sha.slice(0, 10)}\` (header Bot hash \`${input.headerBotHash}\`, tree \`${input.treeBotHash}\`) and ${input.lost.length} card(s) left \`ready\` — a Bot regression (issue #6463). Nothing was committed: the lockfile on the base still carries the verdicts of the previous Bot.`,
        "",
        "**Cards no longer `ready`:**",
        "",
        cards,
        "",
        `**Commit range that moved the Bot hash:** \`${input.range}\`, Bot-source commits:`,
        "",
        commits,
        "",
        '**Desired behavior:** every card above plays again (`bun run oracle:compile --carry-bot --replay-card "<name>"` on the fix, a `must` blade entry per `/bot-change`) — the fix moves the Bot hash and the replay runs again on its own. A freeze ruled CORRECT is acknowledged in `data/oracle-state-regressions.json` (`bun run oracle:mark-regressions`, a human-written reason): the replay then commits without it. Closing this issue alone re-sweeps and re-files it.',
        "",
        "## Band",
        "",
        `P1 — ${input.lost.length} card(s) left \`ready\` under a Bot change: the pool shrank with no PR acknowledging it, and the lockfile header stays on the previous Bot until it is fixed.`,
        "",
    ].join("\n");
}

/**
 * What a push's result means (ADR 0157 § Option 1b, "Coalescing"):
 *
 *   - `landed`: the base tip is the derive commit;
 *   - `coalesced`: the push was refused AND the base moved meanwhile — a
 *     newer tip exists, and its own post-merge run regenerates from scratch;
 *     this commit is dropped, never rebuilt or retried (the hourly cron is
 *     the backstop). Not a failure;
 *   - `failed`: the push was refused and the base did NOT move — the network,
 *     the credentials, a hook: the run's red.
 */
export function pushOutcome(input: {
    readonly pushed: boolean;
    readonly remoteMoved: boolean;
}): "landed" | "coalesced" | "failed" {
    if (input.pushed) return "landed";
    return input.remoteMoved ? "coalesced" : "failed";
}

/** One git invocation, as `spawnSync` answers it; `timedOut` when its
 *  deadline passed. */
export interface GitAnswer {
    readonly status: number | null;
    readonly stdout: string;
    readonly stderr: string;
    readonly timedOut?: boolean;
}

/** Runs `git <args>` in the repository, with an optional deadline. */
export type GitRun = (args: string[], opts?: { timeout?: number }) => GitAnswer;

/** Git's own refusal line (` ! [rejected] … (non-fast-forward)`), never its
 *  multi-line `hint:` block. Pure. */
export function refusalLine(stderr: string, timedOutS?: number): string {
    if (timedOutS !== undefined) return `no answer within ${timedOutS}s`;
    const lines = stderr.split("\n").map((l) => l.trim());
    return (
        lines.find((l) => l.startsWith("! ")) ??
        lines.find((l) => l !== "" && !l.startsWith("hint:")) ??
        "git printed no error"
    );
}

/**
 * Push the derive commit `sha` (built on `head`) to the base and say what
 * happened — the I/O half of {@link pushOutcome}, over an injected runner so
 * a real bare remote can exercise it. On a refusal the base is fetched: a
 * remote tip that IS `sha` is a push that landed while the client timed out
 * (landed, not coalesced); any other tip but `head` is a base that moved
 * (coalesced); `head` itself is a refusal with the base unmoved (failed).
 */
export function pushDerivedCommit(
    git: GitRun,
    input: {
        readonly sha: string;
        readonly head: string;
        readonly baseBranch: string;
        readonly originBase: string;
        readonly netTimeoutMs: number;
    }
): {
    readonly outcome: "landed" | "coalesced" | "failed";
    readonly why: string;
    readonly remoteTip: string;
} {
    const push = git(
        ["push", "-q", "origin", `${input.sha}:refs/heads/${input.baseBranch}`],
        { timeout: input.netTimeoutMs }
    );
    const why = refusalLine(
        push.stderr,
        push.timedOut ? input.netTimeoutMs / 1000 : undefined
    );
    if (push.status === 0)
        return { outcome: "landed", why, remoteTip: input.sha };
    const fetched = git(["fetch", "-q", "origin", input.baseBranch], {
        timeout: input.netTimeoutMs,
    });
    const remoteTip =
        fetched.status === 0
            ? git(["rev-parse", input.originBase]).stdout.trim()
            : input.head;
    if (remoteTip === input.sha) return { outcome: "landed", why, remoteTip };
    return {
        outcome: pushOutcome({
            pushed: false,
            remoteMoved: remoteTip !== input.head,
        }),
        why,
        remoteTip,
    };
}

/** A catalogue file on the tip beside what the tree generates for it. */
export interface CatalogueEntry {
    readonly path: string;
    readonly committed: string | null;
    readonly expected: string;
}

export type Freshness =
    | { readonly fresh: true }
    | { readonly fresh: false; readonly why: string };

/**
 * Is the tip DERIVED-FRESH — may the primary checkout (the local Convex
 * deployment) be fast-forwarded to it? Two questions, the two offline tiers
 * that cost about a second each: `check:oracle`'s header-hash tier
 * (`hashDrift`, the message `headerHashDrift` printed, or null) and
 * `catalogue:check`'s byte comparison of the four catalogue files. Any
 * drift is stale, with the first reason named; a stale tip leaves the primary
 * on the previous fresh tip (ADR 0157 § Option 1b, "Deployment").
 */
export function derivedFreshness(input: {
    readonly hashDrift: string | null;
    readonly catalogue: ReadonlyArray<CatalogueEntry>;
}): Freshness {
    if (input.hashDrift !== null)
        return {
            fresh: false,
            why: `lockfile header: ${input.hashDrift.split("\n")[0]!.trim()}`,
        };
    for (const c of input.catalogue)
        if (c.committed !== c.expected)
            return {
                fresh: false,
                why:
                    c.committed === null
                        ? `${c.path} is missing`
                        : `${c.path} is not what the tree generates`,
            };
    return { fresh: true };
}
