/**
 * The lane's SENTINEL SET (issue #7651, PRD issue #7645): the test files that
 * produced a base RED or a PR lane red in the last `windowDays`, run by every
 * scoped code lane whatever the import graph says.
 *
 * WHY. The REDs of 2026-10-24 → 10-31 were caught by tests the lane skipped —
 * bot files past the cost budget, files the walk never reached
 * (`pickRatings.bot`, 16 ms). History names those files: a test that broke the
 * base or a PR's lane once is the likeliest to break it again. Five of the
 * week's fifteen REDs were such files, for ~3 s per lane.
 *
 * DERIVED, NEVER HAND-PICKED — the lane stays "verbatim" (ADR 0154):
 *
 *   1. `bun run lane:sentinels` (`scripts/lane-sentinels-refresh.ts`) reads
 *      the base's RED verdicts' `tests` (the `health` commit statuses) and
 *      the failing files of the red `queue-lane` runs' `lane.json` over the
 *      window, keeps the test files of a lane project still in the tree, and
 *      joins each one's measured cost (`data/bot-test-costs.json`, the one
 *      per-file cost table: health records a wall for bot files only).
 *   2. `deriveSentinels` applies `capS` cheapest first and `renderSentinels`
 *      writes `SENTINELS_PATH` with a provenance header — a pure function of
 *      the recorded candidates and the cap, so `lane-sentinels.test.ts` pins
 *      that re-deriving the committed file is a no-op (a hand edit, or a cap
 *      changed in config without `--recap`, reds it).
 *   3. `check-lane.ts` runs `sentinels` in the `engine` and `skin` lanes (the
 *      `full` lane already runs their projects whole; `cards` runs none) and
 *      names `overCap` / `unmeasured` in skip lines with their cost.
 *   4. `.github/workflows/bot-costs-refresh.yml` regenerates it weekly and
 *      opens the data PR.
 *
 * The window and the cap are config (`tolaria.config.json` `laneSentinels`,
 * read by this module ONLY), never literals.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

/** The committed sentinel set, repo-relative. */
export const SENTINELS_PATH = "data/lane-sentinels.json";

/** The provenance header every generated file carries, verbatim. */
export const SENTINELS_HEADER =
    "GENERATED by `bun run lane:sentinels` (scripts/lane-sentinels-refresh.ts, issue #7651) — never edit by hand; `bun run lane:sentinels --recap` re-applies a changed cap offline";

/** The branch prefix of the weekly refresh PR: its presence among the open
 *  PRs keeps the job quiet (the bot cost refresh's rule, issue #6999). */
export const SENTINELS_BRANCH_PREFIX = "chore/lane-sentinels-refresh-";

export interface SentinelConfig {
    /** How many days of verdicts and lane records the generator reads. */
    windowDays: number;
    /** The admitted files' summed cost never exceeds this. */
    capMs: number;
}

/** One file the evidence names, with what named it and what it costs. */
export interface SentinelCandidate {
    /** Repo-relative, posix. */
    file: string;
    /** RED `health` verdicts on the base naming it. */
    reds: number;
    /** Red `queue-lane` runs that failed in it. */
    laneReds: number;
    /** Measured cost, ms; `null` = no row in the cost table. */
    ms: number | null;
}

export interface LaneSentinels {
    $generated: string;
    version: 1;
    /** Provenance: the window the evidence was read over. */
    windowDays: number;
    /** Provenance: the window's last day, `YYYY-MM-DD`. */
    through: string;
    /** The cap the derivation applied, seconds. */
    capS: number;
    /** Every file the evidence named, by path — the derivation's input. */
    candidates: SentinelCandidate[];
    /** Admitted, cheapest first (ties by path). */
    sentinels: { file: string; ms: number }[];
    /** Measured, but past the cap once the cheaper ones were in. */
    overCap: { file: string; ms: number }[];
    /** No measured cost: named, never admitted on a guess. */
    unmeasured: string[];
}

/** `tolaria.config.json` `laneSentinels`; a missing or malformed key throws —
 *  a lane that silently ran no sentinel is the gap this closes. */
export function readSentinelConfig(root: string): SentinelConfig {
    const config = JSON.parse(
        readFileSync(join(root, "tolaria.config.json"), "utf8")
    ) as { laneSentinels?: Record<string, unknown> };
    const c = config.laneSentinels;
    const num = (k: string): number => {
        const v = c?.[k];
        if (typeof v !== "number" || !(v > 0))
            throw new Error(
                `tolaria.config.json: laneSentinels.${k} must be a positive number`
            );
        return v;
    };
    return { windowDays: num("windowDays"), capMs: num("capS") * 1000 };
}

/** The committed set; absent file → `null` (a lane then runs no sentinel and
 *  says so). */
export function readLaneSentinels(root: string): LaneSentinels | null {
    const p = join(root, SENTINELS_PATH);
    if (!existsSync(p)) return null;
    return JSON.parse(readFileSync(p, "utf8")) as LaneSentinels;
}

/**
 * The candidates the evidence names: per file, how many RED verdicts and red
 * lane runs named it, joined with its cost. `keep` is the tree's say — a test
 * file of a lane project that still exists; anything else (a deleted file, a
 * perf or ladder file, a non-test path) is no candidate.
 */
export function collectCandidates(
    redTests: readonly (readonly string[])[],
    laneRedFiles: readonly (readonly string[])[],
    costs: Readonly<Record<string, number>>,
    keep: (file: string) => boolean
): SentinelCandidate[] {
    const by = new Map<string, SentinelCandidate>();
    const bump = (
        lists: readonly (readonly string[])[],
        key: "reds" | "laneReds"
    ) => {
        for (const list of lists)
            for (const file of new Set(list)) {
                if (!keep(file)) continue;
                const c = by.get(file) ?? {
                    file,
                    reds: 0,
                    laneReds: 0,
                    ms: costs[file] ?? null,
                };
                c[key]++;
                by.set(file, c);
            }
    };
    bump(redTests, "reds");
    bump(laneRedFiles, "laneReds");
    return [...by.values()].sort((a, b) => (a.file < b.file ? -1 : 1));
}

/** The cap, cheapest first (ties by path); an unmeasured file is named,
 *  never admitted at a guessed cost. */
export function deriveSentinels(
    candidates: readonly SentinelCandidate[],
    capMs: number
): Pick<LaneSentinels, "sentinels" | "overCap" | "unmeasured"> {
    const measured = candidates
        .filter((c): c is SentinelCandidate & { ms: number } => c.ms !== null)
        .map((c) => ({ file: c.file, ms: c.ms }))
        .sort((a, b) => a.ms - b.ms || (a.file < b.file ? -1 : 1));
    const sentinels: { file: string; ms: number }[] = [];
    const overCap: { file: string; ms: number }[] = [];
    let total = 0;
    for (const m of measured) {
        if (total + m.ms > capMs) overCap.push(m);
        else {
            sentinels.push(m);
            total += m.ms;
        }
    }
    const unmeasured = candidates
        .filter((c) => c.ms === null)
        .map((c) => c.file)
        .sort();
    return { sentinels, overCap, unmeasured };
}

/** The whole file from its inputs. */
export function buildLaneSentinels(
    candidates: readonly SentinelCandidate[],
    config: SentinelConfig,
    through: string
): LaneSentinels {
    return {
        $generated: SENTINELS_HEADER,
        version: 1,
        windowDays: config.windowDays,
        through,
        capS: config.capMs / 1000,
        candidates: [...candidates],
        ...deriveSentinels(candidates, config.capMs),
    };
}

export function renderSentinels(s: LaneSentinels): string {
    return `${JSON.stringify(s, null, 4)}\n`;
}

/** Whether two sets admit and name the same files at the same costs — the
 *  candidates' counts and the window are provenance: a refresh that moves
 *  only them is no change, so no PR. */
export function sameSentinels(
    a: LaneSentinels,
    b: LaneSentinels | null
): boolean {
    if (b === null) return false;
    const key = (s: LaneSentinels) =>
        JSON.stringify([s.capS, s.sentinels, s.overCap, s.unmeasured]);
    return key(a) === key(b);
}

/** The failing test files of one red `queue-lane` run's `lane.json`: every
 *  `fail` outcome's `failedFiles` (a step cured by its re-run is a flake, not
 *  a red). `null`, torn or green JSON → none. */
export function laneRedFiles(text: string | null): string[] {
    if (text === null || text.trim() === "") return [];
    let raw: unknown;
    try {
        raw = JSON.parse(text);
    } catch {
        return [];
    }
    if (typeof raw !== "object" || raw === null) return [];
    const r = raw as { ok?: unknown; outcomes?: unknown };
    if (r.ok !== false || !Array.isArray(r.outcomes)) return [];
    const out = new Set<string>();
    for (const o of r.outcomes as unknown[]) {
        if (typeof o !== "object" || o === null) continue;
        const { status, failedFiles } = o as {
            status?: unknown;
            failedFiles?: unknown;
        };
        if (status !== "fail" || !Array.isArray(failedFiles)) continue;
        for (const f of failedFiles) if (typeof f === "string") out.add(f);
    }
    return [...out].sort();
}
