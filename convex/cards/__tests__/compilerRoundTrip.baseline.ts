/**
 * The defect is on the HAND-WRITTEN side: the compiler's reading is the
 * CR-faithful one.
 *
 * Usually that means fixing the card graduates the row — but not always:
 * Ashnod's Altar, the last row here, was the counter-example. Its reading was
 * right and the remedy was engine-side first (issue #3455 taught the non-stack
 * mana path to pay a filtered sacrifice), and only then the card flip that
 * graduated it (issue #3047). "Card-defect" names the SIDE the defect is on,
 * never the shape of its fix.
 *
 * Every row is now an adjudicated mismatch carrying its ticket inline. The
 * `no-oracle-text` half — 23 definitions that omitted `oracleText` entirely, so
 * the compiler's input was missing rather than empty — is gone: issue #3075
 * backfilled the field, 15 graduated on the spot and the 8 with real rules text
 * moved to `COMPILER_GAP_ROWS` as `unparsed`, which is what a card with an
 * Oracle line no grammar slot reads has always meant. The class cannot reopen:
 * `convex/oracle/__tests__/gold.test.ts` pins `withoutOracleText` at zero, and
 * that assertion is the durable guard, not the backfill.
 */
export const CARD_DEFECT_ROWS: readonly string[] = [];

/**
 * The compiler produced a definition, the two disagree, and which encoding is
 * canonical is an open question rather than a defect on either side.
 *
 * Empty since issue #3823: its last two rows (Horror of Horrors, Lava Dart)
 * were one question — a sacrifice cost naming a LAND TYPE written as
 * `{ types: ["Land"], subtypes: [...] }` beside the compiler's
 * `{ subtypes: [...] }`. CR 205.3i puts land types on lands only, so both
 * cards now write the subtype alone.
 */
export const UNDETERMINED_ROWS: readonly string[] = [];

const rows = (
    names: readonly string[],
    direction: BaselineRow["direction"]
): BaselineRow[] => names.map((name) => ({ name, direction }));

/**
 * The three classes as one list, sorted by name — what `triageBaseline` and
 * Guard C consume. Derived, never hand-maintained: a name appears here because
 * it appears in exactly one of the arrays above.
 */
export const BASELINE_ROWS: readonly BaselineRow[] = [
    ...rows(COMPILER_GAP_ROWS, "compiler-gap"),
    ...rows(CARD_DEFECT_ROWS, "card-defect"),
    ...rows(UNDETERMINED_ROWS, "undetermined"),
].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

/** The baseline's names alone — the exemption lookup Guard C does per card. */
export const COMPILER_ROUND_TRIP_BASELINE: readonly string[] =
    BASELINE_ROWS.map((row) => row.name);
