// Shared test helpers for the NCC per-colour test files (ADR 0043 split).
// Stack-push / resolve shims mirroring the other sets' helpers. Fixture
// builders (makeInstance/makePlayer/makeState) stay in
// convex/cards/__tests__/setup.ts.

import {
    type CardInstanceState,
    type GameState,
    resolveTopOfStack,
    type StackItem,
} from "../../../../gre/state";

export function resolveActivated(
    state: GameState,
    source: CardInstanceState,
    abilityId: string,
    targets: StackItem["targets"] = []
): void {
    state.stack.push({
        ...source,
        zone: "stack",
        castById: source.controllerId,
        abilityId,
        targets,
    });
    resolveTopOfStack(state);
}

export function resolveTrigger(
    state: GameState,
    source: CardInstanceState,
    triggeredAbilityId: string,
    triggerEvent: StackItem["triggerEvent"],
    targets: StackItem["targets"] = []
): void {
    state.stack.push({
        ...source,
        zone: "stack",
        castById: source.controllerId,
        triggeredAbilityId,
        triggerSourceId: source.id,
        triggerEvent,
        targets,
    });
    resolveTopOfStack(state);
}

/** Answers the head pending choice (`requestChoice` picks, or a `requestMayPay`
 *  `["yes"]`/`["no"]`) and resumes resolution. */
export function answerChoice(state: GameState, picks: string[]): void {
    const head = state.pendingChoices?.[0];
    if (!head) throw new Error("no pending choice to answer");
    const item = state.stack.find((s) => s.id === head.stackItemId)!;
    item.collectedChoices = {
        ...(item.collectedChoices ?? {}),
        [`${head.step}:${head.choiceId}`]: picks,
    };
    state.pendingChoices = undefined;
    resolveTopOfStack(state);
}
