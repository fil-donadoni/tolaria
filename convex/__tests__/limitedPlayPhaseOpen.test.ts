// Limited Event play phase opens (PRD #1628, ADR 0076, issue #1644):
// "completing the last seat's deck moves the event to `playing` and creates
// round 1 with exactly one pairing slot per seat".
//
// The project has no convex-test harness (see `convex/__tests__/adminAuth.test.ts`),
// so — exactly as `limitedEvents.test.ts` and `limitedChallenge.test.ts` do —
// this drives the EXACT exported functions `openPlayPhaseIfReady`
// (`convex/limitedEvents.ts`) calls, in the SAME order, against the REAL card
// registry and the REAL checked-in LEA Booster Config. Every observable claim
// is then asserted THROUGH `projectLimitedEvent`, the seam the client actually
// receives — never a hand-built view.
